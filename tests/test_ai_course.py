def test_practice_gates_the_ai_quiz(client, ai_catalog):
    first = ai_catalog.lessons[0]["id"]
    quiz = _answers(_lesson(ai_catalog, first)["quiz"])

    blocked = client.post("/api/quiz/%s" % first, json=quiz).get_json()
    assert blocked["ok"] is False and blocked["error"] == "practice"

    _solve(client, ai_catalog, first)
    passed = client.post("/api/quiz/%s" % first, json=quiz).get_json()
    assert passed["passed"], passed
    assert client.get("/lesson/%s" % ai_catalog.lessons[1]["id"]).status_code == 200


def test_switching_courses_keeps_each_course_progress(client, ai_catalog, py_catalog):
    ai_first = ai_catalog.lessons[0]["id"]
    _solve(client, ai_catalog, ai_first)
    client.post("/api/quiz/%s" % ai_first, json=_answers(_lesson(ai_catalog, ai_first)["quiz"]))

    assert switch_course(client, "pybook").status_code == 302
    py_first = py_catalog.lessons[0]["id"]
    assert client.get("/lesson/%s" % py_first).status_code == 200
    assert client.get("/lesson/%s" % py_catalog.lessons[1]["id"]).status_code == 403
    _solve(client, py_catalog, py_first)
    client.post("/api/quiz/%s" % py_first, json=_answers(_lesson(py_catalog, py_first)["quiz"]))

    assert switch_course(client, "ai").status_code == 302
    assert client.get("/lesson/%s" % ai_catalog.lessons[1]["id"]).status_code == 200
    state = client.get("/api/export").get_json()
    assert ai_first in state["lessons"] and py_first in state["lessons"]


def test_ai_module_exam_unlocks_only_after_every_lesson(client, ai_catalog):
    """The page explains what is left; the API is what actually refuses."""
    module = ai_catalog.modules[0]["id"]
    page = client.get("/exam/%s" % module).get_data(as_text=True)
    assert "Pass these 5 lessons first" in page
    early = client.post("/api/exam/%s" % module, json={"answers": {}}).get_json()
    assert early["ok"] is False and early["error"] == "lessons"
    assert client.get("/skip/%s" % module).status_code == 200


def test_ai_whole_course_can_be_completed_through_the_api(client, ai_catalog):
    for module in ai_catalog.modules:
        for lesson in ai_catalog.module_lessons(module["id"]):
            _solve(client, ai_catalog, lesson["id"])
            data = client.post(
                "/api/quiz/%s" % lesson["id"],
                json=_answers(_lesson(ai_catalog, lesson["id"])["quiz"]),
            ).get_json()
            assert data["passed"], "%s: %s" % (lesson["id"], data)
        exam = client.post(
            "/api/exam/%s" % module["id"],
            json={"answers": _answers(ai_catalog.full(module["id"])["exam"])},
        ).get_json()
        assert exam["passed"], "%s exam: %s" % (module["id"], exam)

    assert len(client.get("/api/export").get_json()["lessons"]) == len(ai_catalog.lessons)
    assert "Course complete" in client.get("/learn").get_data(as_text=True)
