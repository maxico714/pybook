"""Tests for the AI-engineering course: content integrity and the live flow.

The course is generated by ``python -m pybook.build_ai_course``; these tests
check the shipped files, not the builder, so a stale or hand-edited data folder
fails here.  Every check that matters runs the real sandbox: an exercise whose
solution does not pass, or an example whose ``output`` is not what Python
actually prints, is a content bug that a learner would hit.
"""
from __future__ import annotations

import pathlib
import sys

import pytest

ROOT = pathlib.Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from web.content import Catalog  # noqa: E402
from web.runner import check_exercise, run_code  # noqa: E402
from helpers import csrf, signed_in, switch_course  # noqa: E402

DATA = ROOT / "pybook" / "data"
AI = DATA / "ai"


# --------------------------------------------------------------------- fixtures
@pytest.fixture(scope="module")
def ai_catalog() -> Catalog:
    return Catalog(AI)


@pytest.fixture(scope="module")
def py_catalog() -> Catalog:
    return Catalog(DATA)


@pytest.fixture()
def client(app):
    """An approved learner whose selected course is the AI course."""
    return signed_in(app, course="ai")


def _answers(items: list[dict]) -> dict:
    return {"q%d" % (index + 1): item["answer"] for index, item in enumerate(items)}


def _lesson(catalog: Catalog, lesson_id: str) -> dict:
    return catalog.lesson(lesson_id)


def _solve(client, catalog: Catalog, lesson_id: str) -> None:
    for exercise in _lesson(catalog, lesson_id)["exercises"]:
        data = client.post(
            "/api/check/%s" % exercise["id"], json={"code": exercise["solution"]}
        ).get_json()
        assert data["passed"], "%s: %s" % (exercise["id"], data)


# --------------------------------------------------------------------- content
def test_course_shape(ai_catalog):
    assert ai_catalog.index["id"] == "ai"
    assert len(ai_catalog.modules) == 5
    assert len(ai_catalog.lessons) == 23
    assert [module["id"] for module in ai_catalog.modules] == [
        "ai-m01",
        "ai-m02",
        "ai-m03",
        "ai-m04",
        "ai-m05",
    ]


def test_module_ids_never_collide_with_the_python_course(ai_catalog, py_catalog):
    """Progress rows are keyed by module id, so the two courses must not share one."""
    assert not {module["id"] for module in ai_catalog.modules} & {
        module["id"] for module in py_catalog.modules
    }
    assert not set(ai_catalog.by_lesson) & set(py_catalog.by_lesson)


def test_every_lesson_is_complete(ai_catalog):
    problems = []
    for lesson in ai_catalog.lessons:
        body = _lesson(ai_catalog, lesson["id"])
        if not body["intro"].get("en") or not body["intro"].get("hinglish"):
            problems.append((lesson["id"], "intro"))
        if not body["real_life"].get("en"):
            problems.append((lesson["id"], "real_life"))
        if not body["takeaway"].get("en"):
            problems.append((lesson["id"], "takeaway"))
        if not body["keywords"]:
            problems.append((lesson["id"], "keywords"))
        if not body["examples"]:
            problems.append((lesson["id"], "examples"))
        if not body["exercises"]:
            problems.append((lesson["id"], "exercises"))
        if len(body["quiz"]) < 3:
            problems.append((lesson["id"], "quiz"))
    assert not problems, problems


def test_every_quiz_answer_points_at_an_option(ai_catalog):
    problems = []
    for module in ai_catalog.modules:
        full = ai_catalog.full(module["id"])
        banks = [full["exam"], full["skip_exam"]]
        banks += [_lesson(ai_catalog, lesson["id"])["quiz"] for lesson in ai_catalog.module_lessons(module["id"])]
        for bank in banks:
            for item in bank:
                letter = item["answer"]
                if not (len(letter) == 1 and "a" <= letter < chr(ord("a") + len(item["options"]))):
                    problems.append((item["id"], letter))
                if len(set(item["options"])) != len(item["options"]):
                    problems.append((item["id"], "duplicate option"))
    assert not problems, problems


def test_every_solution_passes_its_own_checks(ai_catalog):
    """The real gate: the shipped solution must pass the shipped checks."""
    failures = []
    for lesson in ai_catalog.lessons:
        for exercise in _lesson(ai_catalog, lesson["id"])["exercises"]:
            result = check_exercise(exercise["solution"], exercise["checks"])
            if not result["passed"]:
                failures.append((exercise["id"], result.get("error") or result["checks"]))
    assert not failures, failures


def test_every_example_output_is_what_python_prints(ai_catalog):
    """No hand-written outputs: the expected output is a recorded real run."""
    wrong = []
    for lesson in ai_catalog.lessons:
        for example in _lesson(ai_catalog, lesson["id"])["examples"]:
            result = run_code(example["code"])
            if not result["ok"]:
                wrong.append((lesson["id"], result.get("error")))
            elif example["output"].strip("\n") != (result["stdout"] or "").strip("\n"):
                wrong.append((lesson["id"], "output drift"))
    assert not wrong, wrong


def test_skip_exam_is_fair_and_harder_than_the_module_exam(ai_catalog):
    """90% of a small bank would mean a perfect score, so the bank is broadened."""
    for module in ai_catalog.modules:
        full = ai_catalog.full(module["id"])
        assert len(full["exam"]) == 6
        assert len(full["skip_exam"]) >= 8, module["id"]
        assert len(full["skip_exam"]) > len(full["exam"])
        ids = [item["id"] for item in full["skip_exam"]]
        assert len(ids) == len(set(ids)), module["id"]


